	/**
	 * Load and parse a bulk-run log file for display in the UI.
	 *
	 * `$data` keys consumed:
	 * - `type`    string  'media' or 'custom' — keys the response namespace.
	 * - `logFile` string  Base filename (without '.log') passed from the dispatch layer.
	 *             This is originally read from `$_POST['loadFile']` in `ajaxRequest()`.
	 *
	 * Parses the semicolon-delimited log file into row arrays with date, filename, id,
	 * error, link, kblink, and (for custom) path fields.  Prepends a header row.
	 *
	 * Returns:
	 * - `$json->$type->logType`  string  'media' or 'custom'.
	 * - `$json->$type->title`    string  Formatted "Bulk ran on …" heading.
	 * - `$json->$type->results`  array   Parsed rows (first row = headers).
	 * - `$json->$type->is_error` bool    (Optional) true when the file cannot be found.
	 * - `$json->$type->result`   string  (Optional) Error message text.
	 *
	 * @param \stdClass $json JSON accumulator object.
	 * @param array     $data Dispatch data array with 'logFile' and 'type'.
	 * @return \stdClass Updated JSON response object.
	 */
	protected function loadLogFile($json, $data)
	{
		$logFile = $data['logFile'] . '.log';
		$type = $data['type'];
		$fs = \wpSPIO()->filesystem();

		if (is_null($logFile)) {
			$json->$type->is_error = true;
			$json->$type->result = __('Could not load log file', 'shortpixel-image-optimiser');
			return $json;
		}

		$bulkController = BulkController::getInstance();
		$log = $bulkController->getLog($logFile);
		$logData = $bulkController->getLogData($logFile);

		$logType = $logData['type']; // custom or media.

		$json->$type->logType = $logType;

		if (false === $log) {
			$json->$type->is_error = true;
			$json->$type->result = __('Log file does not exist', 'shortpixel-image-optimiser');
			return $json;
		}

		$date = (isset($logData['date'])) ? UiHelper::formatTS($logData['date']) : false;
		$content = trim($log->getContents());
		$lines = array_filter(explode(';', $content));

		$headers = [
			__('Time', 'shortpixel-image-optimiser'),
			__('Filename', 'shortpixel-image-optimiser'),
			__('ID', 'shortpixel-image-optimiser'),
			__('Error', 'shortpixel-image-optimiser'),
		];

		if ('custom' == $logType) {
			array_splice($headers, 3, 0, __('Info', 'shortpixel-image-optimiser'));
		}

		foreach ($lines as $index => $line) {
			$cells = array_filter(explode('|', $line));

			$date = $cells[0];
			$filename = $cells[1];
			$id = isset($cells[2]) ? $cells[2] : false;
			$error = isset($cells[3]) ? $cells[3] : false;

			$line = ['date' => $date, 'filename' => $filename, 'id' => $id, 'error' => $error];

			if ($id !== false && $logType !== 'custom') {
				// replaces the image id with a link to image.
				$line['link'] = esc_url(admin_url('post.php?post=' . trim($id) . '&action=edit'));
			} elseif ($logType === 'custom') {
				$base = esc_url(admin_url('upload.php?page=wp-short-pixel-custom'));
				$line['link'] = add_query_arg('s', sanitize_text_field($filename), $base);
			}

			if ($error !== false) {
				$line['kblink'] = UiHelper::getKBSearchLink($error);
			}

			if ('custom' == $logType && $id !== false) {
				$imageObj = $fs->getImage($id, 'custom');
				if (is_object($imageObj)) {
					$dir = $imageObj->getFileDir();
					if (is_object($dir)) {
						$path = $dir->getRelativePath();
						$line['path'] = $path;
					}
				}
			}

			$lines[$index] = $line;
		}
		$lines = array_values(array_filter($lines));
		array_unshift($lines, $headers);
		$json->$type->title = sprintf(__('Bulk ran on %s', 'shortpixel-image-optimiser'), $date);
		$json->$type->results = $lines;
		return $json;
	}

	/**
	 * Verify the WordPress nonce for the current AJAX request.
	 *
	 * Reads `$_POST['nonce']` and validates it against `$action`.  On failure, sends
	 * a JSON error response with `error = NONCE_FAILED` and exits.  This method does
	 * not return false — a failed nonce always terminates the request.
	 *
	 * @param string $action The nonce action string (e.g. 'processing', 'ajax_request').
	 * @return void  Returns normally on success; exits on failure.
	 */
	protected function checkNonce($action)
	{
		if (! wp_verify_nonce($_POST['nonce'], $action)) {

			$id = isset($_POST['id']) ? intval($_POST['id']) : false;
			$action = isset($_POST['screen_action']) ? sanitize_text_field($_POST['screen_action']) : false;

			$json = new \stdClass;
			$json->message = __('Nonce is missing or wrong - Try to refresh the page', 'shortpixel-image-optimiser');
			$json->item_id = $id;
			$json->action = $action;
			$json->status = false;
			$json->error = self::NONCE_FAILED;
			$this->send($json);
			exit();
		}
	}

	/**
	 * Verify that the current user has the required capability for an action.
	 *
	 * Delegates to `AccessModel::userIsAllowed()` with the provided `$access` level
	 * (e.g. 'is_author', 'is_editor', 'is_admin_user', 'is_super_admin' — the latter
	 * used by the site-wide tools `toolsRemoveAll` / `toolsRemoveBackup`). On failure,
	 * sends a JSON error with `error = NO_ACCESS` and exits.
	 *
	 * @param string $action The action name (used only for the error message).
	 * @param string $access The capability level string as understood by AccessModel.
	 * @return true  Returns true on success; exits on failure.
	 */
	protected function checkActionAccess($action, $access)
	{
		$accessModel = AccessModel::getInstance();

		$bool = $accessModel->userIsAllowed($access);

		if ($bool === false) {
			$json = new \stdClass;
			$json->message = __('This user is not allowed to perform this action', 'shortpixel-image-optimiser');
			$json->action = $action;
			$json->status = false;
			$json->error = self::NO_ACCESS;
			$this->send($json);
			exit();
		}

		return true;
	}

	/**
	 * Verify that the current user may edit the given image.
	 *
	 * Accepts either a valid image model object or a non-object (false/null) for cases
	 * where the image could not be loaded.  Calls `AccessModel::imageIsEditable()`.
	 * On failure (image not found or user not allowed), sends a JSON error with
	 * `error = NO_ACCESS` and exits.
	 *
	 * @param \ShortPixel\Model\Image\ImageModel|false $mediaItem The image model to check, or false.
	 * @return true  Returns true on success; exits on failure.
	 */
	protected function checkImageAccess($mediaItem)
	{

		// defaults
		$message = __('This user is not allowed to edit this image', 'shortpixel-image-optimiser');

		$accessModel = AccessModel::getInstance();
		if (is_object($mediaItem)) {
			$bool = $accessModel->imageIsEditable($mediaItem);
			$id = $mediaItem->get('id');

		} else {
			$bool = false;
			$id = false;
			if (! is_object($mediaItem))
			{
				$message = __('Image does not exist or could not be loaded', 'shortpixel-image-optimiser');
			}
		}

		if ($bool === false) {
			$json = new \stdClass;
			$json->message = $message; 
			$json->status = false;
			$json->id = $id;
			$json->error = self::NO_ACCESS;
			$this->send($json);
			exit();
		}

		return true;
	}

	/**
	 * Send a JSON response to the browser and terminate the request.
	 *
	 * Casts non-stdClass objects to stdClass to avoid serialisation issues.  Appends
	 * `callback` from `$_POST['callback']` (if present) and the current processor key
	 * to the response before calling `wp_send_json()`.
	 *
	 * @param \stdClass|array|object $json The response payload to serialise.
	 * @return void  Always exits via wp_send_json().
	 */
	protected function send($json)
	{
		// Cast before sending anything to a simple stdclass, to prevent issues with adding json and processorkey to output 
		if ( (is_object($json) && false === $json instanceof \stdClass)  || is_array($json))
		{
			$json = (object) $json; 
		}

		$callback = isset($_POST['callback']) ? sanitize_text_field($_POST['callback']) : false;
		if ($callback)
			$json->callback = $callback; // which type of request we just fullfilled ( response processing )

		$pKey = $this->getProcessorKey();
		if ($pKey !== false)
			$json->processorKey = $pKey;

		wp_send_json($json);
		exit();
	}


	/**
	 * Hard-uninstall the plugin: remove all data and deactivate.
	 *
	 * Verifies a secondary nonce from `$_POST['tools-nonce']` (action 'remove-all')
	 * in addition to the outer `ajax_request` nonce.  On success, calls
	 * `InstallHelper::hardUninstall()` and redirects to the plugins page.
	 *
	 * Returns:
	 * - `$json->settings->results`  string  Confirmation or (logged) error message.
	 * - `$json->settings->redirect` string  URL to redirect the browser to.
	 *
	 * @param \stdClass $json JSON accumulator object.
	 * @param array     $data Dispatch data array (unused).
	 * @return \stdClass Updated JSON response object.
	 */
	private function removeAllData($json, $data)
	{
		if (1 === wp_verify_nonce($_POST['tools-nonce'], 'remove-all')) {
			InstallHelper::hardUninstall();
			$json->settings->results = __('All Data has been removed. The plugin has been deactivated', 'shortpixel-image-optimiser');
		} else {
			Log::addError('RemoveAll detected with wrong nonce');
		}

		$json->settings->redirect = admin_url('plugins.php');

		return $json;
	}

	/**
	 * Delete all ShortPixel backup files from the backup folder.
	 *
	 * Verifies a secondary nonce from `$_POST['tools-nonce']` (action 'empty-backup').
	 * Moves log files to a temp directory, recursively deletes the backup folder, then
	 * moves log files back.
	 *
	 * Returns:
	 * - `$json->settings->results` string  Confirmation or error text.
	 *
	 * @param \stdClass $json JSON accumulator object.
	 * @param array     $data Dispatch data array (unused).
	 * @return \stdClass Updated JSON response object.
	 */
	private function removeBackup($json, $data)
	{
		if (wp_verify_nonce($_POST['tools-nonce'], 'empty-backup')) {			

			$fs = \wpSPIO()->filesystem(); 
			
			$fs->moveLogFiles(); 

			$dir = \wpSPIO()->filesystem()->getDirectory(SHORTPIXEL_BACKUP_FOLDER);
			$dir->recursiveDelete(); 

			$fs->moveLogFiles(['to_temp' => false]);

			$json->settings->results = __('The backups have been removed. You can close the window', 'shortpixel-image-optimiser');
		} else {
			$json->settings->results = __('Error: Invalid Nonce in empty backups', 'shortpixel-image-optimiser');
		}

		return $json;
	}
