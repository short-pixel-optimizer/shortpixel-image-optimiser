	 *
	 * Drops the item from the queue if it is currently enqueued, then adds it back with
	 * `action => 'restore'` so the queue processor can run the restore pipeline.
	 *
	 * `$data` keys consumed:
	 * - `id`   int    Image ID.
	 * - `type` string 'media' or 'custom'.
	 *
	 * Returns:
	 * - `$json->$type->results` array  Single-element array with the queue result.
	 * - `$json->status`         bool   true.
	 *
	 * @param \stdClass $json JSON accumulator object.
	 * @param array     $data Dispatch data array with 'id' and 'type'.
	 * @return \stdClass Updated JSON response object.
	 */
	protected function restoreItem($json, $data)
	{
		$id = $data['id'];
		$type = $data['type'];

		$imageModel = $this->getMediaItem($id, $type);

		$this->checkImageAccess($imageModel);

		$queueController = new QueueController();
		$is_in_queue = $queueController->isItemInQueue($imageModel, null);

		if (true === $is_in_queue)
		{
			$queue = $queueController->getQueue($imageModel->get('type')); 
			$queue->dropItem($id);
		}

		$result = $queueController->addItemToQueue($imageModel, ['action' => 'restore']);

		$json->$type->results = [$result];
		$json->status = true;
		return $json;
	}

