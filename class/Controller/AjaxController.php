	/**
	 * Callback for the WP/LR Sync `wpls_update_media` action.
	 *
	 * Lightroom has updated a media item: deletes existing optimisation data, flushes
	 * the filesystem cache, and re-queues the image for optimisation.
	 *
	 * @integration WP / LR Sync (https://meowapps.com/plugin/wplr-sync/)
	 * @param int $imageId WordPress attachment post ID of the updated item.
	 * @return mixed Queue result from `QueueController::addItemToQueue()`.
	 */
	public function onWpLrUpdateMedia($imageId)
	{

		// Get and remove Meta
		$mediaItem = \wpSPIO()->filesystem()->getImage($imageId, 'media');

		$mediaItem->onDelete();

		// Flush and reaquire image to make sure it doesn't stay previous state.
		\wpSPIO()->filesystem()->flushImage($mediaItem);
		$mediaItem = \wpSPIO()->filesystem()->getImage($imageId, 'media', false);

		// Optimize
		$control = new QueueController();
		$json = $control->addItemToQueue($mediaItem);

		return $json;
	}

