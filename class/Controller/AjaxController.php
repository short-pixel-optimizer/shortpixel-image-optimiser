	/**
	 * Register a new custom media folder and return its rendered list-row HTML.
	 *
	 * Reads `$_POST['relpath']` (string, relative path under the WP file base).
	 * Delegates to `OtherMediaController::addDirectory()`.  On success, renders the
	 * single-item view via `OtherMediaFolderViewController::singleItemView()`.
	 *
	 * Also appends any newly queued admin notices to the response.
	 *
	 * Returns:
	 * - `$json->folder->result->id`       int    The new folder's database ID.
	 * - `$json->folder->result->itemView` string Rendered HTML for the folder row.
	 * - `$json->folder->is_error`         bool   (Optional) true on failure.
	 * - `$json->folder->message`          string (Optional) Error message.
	 * - `$json->notices`                  array  (Optional) New admin notice objects.
	 * - `$json->display_notices`          array  (Optional) Display-ready notice HTML.
	 *
	 * @param \stdClass $json JSON accumulator object.
	 * @param array     $data Dispatch data array (unused; values read from $_POST).
	 * @return \stdClass Updated JSON response object.
	 */
	protected function addCustomFolder($json, $data)
	{
		$relpath = isset($_POST['relpath']) ? sanitize_text_field($_POST['relpath']) : null;

		$fs = \wpSPIO()->filesystem();

		$customFolderBase = $fs->getWPFileBase();
		$basePath = $customFolderBase->getPath();

		$path = trailingslashit($basePath) . $relpath;

		$otherMedia = OtherMediaController::getInstance();

		// Result is a folder object
		$result = $otherMedia->addDirectory($path);

		if (false === $result) {
			$json->folder->is_error = true;
			$json->folder->message = __('Failed to add Folder', 'shortpixel-image-optimiser');
		} else {
			$control = new OtherMediaFolderViewController();
			$itemView = $control->singleItemView($result);

			$json->folder->result = new \stdClass;
			$json->folder->result->id = $result->get('id');
			$json->folder->result->itemView = $itemView;
		}

		$noticeController = Notices::getInstance();
		$json->notices = $noticeController->getNewNotices();

		if (count($json->notices) > 0) {
			$json->display_notices = [];
			foreach ($json->notices as $notice) {
				$json->display_notices[] = $notice->getForDisplay(['class' => 'is_ajax', 'is_removable' => false]);
			}
		}
		$noticeController->update(); // dismiss one-time ponies
		return $json;
	}

