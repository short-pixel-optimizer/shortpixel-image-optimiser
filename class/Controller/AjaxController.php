/**
 * Central AJAX dispatch table for the ShortPixel Image Optimiser plugin.
 *
 * ## Registered WP AJAX actions
 *
 * Every public `ajax_*` method and the two primary entry points are registered as WP
 * AJAX actions by the caller (typically `FrontController` or `ShortPixelPlugin`):
 *
 * - `wp_ajax_shortpixel_process_queue`   → ajax_processQueue()
 * - `wp_ajax_shortpixel_ajax`            → ajaxRequest()
 * - `wp_ajax_shortpixel_settings`        → settingsRequest()
 * - `wp_ajax_shortpixel_checkquota`      → ajax_checkquota()
 *
 * ## Request routing
 *
 * `ajaxRequest()` reads `$_POST['screen_action']` and routes to a dedicated protected
 * method.  Item-level actions (`optimizeItem`, `restoreItem`, `reOptimizeItem`, etc.)
 * work on a single `$_POST['id']` + `$_POST['type']` pair.  Bulk and settings actions
 * (`createBulk`, `startBulk`, `finishBulk`, `applyBulkSelection`, `startRestoreAll`,
 * `toolsRemoveAll`, `toolsRemoveBackup`, `loadLogFile`, …) are also dispatched here.
 *
 * `settingsRequest()` reads `$_POST['screen_action']` and routes every recognised
 * settings form action to `settingsFormSubmit()`, which delegates to
 * `SettingsViewController`.
 *
 * ## Authentication / authorisation
 *
 * 1. Every public entry point calls `checkNonce()` first; a bad or missing nonce sends
 *    a JSON error with `error = NONCE_FAILED` and exits.
 * 2. `checkActionAccess()` maps each action to a minimum capability level via
 *    `AccessModel::userIsAllowed()`.  On failure it sends `error = NO_ACCESS` and exits.
 * 3. Image-scoped actions additionally call `checkImageAccess()` which verifies
 *    `AccessModel::imageIsEditable()`.
 * 4. Queue-processing calls `checkProcessorKey()` to ensure only one JS processor
 *    drives the queue at a time; competing tabs receive `error = PROCESSOR_ACTIVE`.
 *
 * ## Response shape
 *
 * All responses go through `send()`, which calls `wp_send_json()` and exits.  The
 * JSON payload always contains `status` (bool/int) and, when set, `error` (one of the
 * class constants below).  The current `processorKey` is appended to every response so
 * that the JS side can update its session token.
 *
 * @package ShortPixel\Controller
 */
class AjaxController
{
	/** Sent when a second JS processor tries to claim the queue while one is already active. */
	const PROCESSOR_ACTIVE = -1;
	/** Sent when `wp_verify_nonce()` returns false. */
	const NONCE_FAILED = -2;
	/** Sent when `screen_action` does not match any known case in the dispatch switch. */
	const NO_ACTION = -3;
	/** Sent when the API key check fails (reserved, not yet used in dispatch). */
	const APIKEY_FAILED = -4;
	/** Sent when no image credits remain (reserved). */
	const NOQUOTA = -5;
	/** Sent on unrecoverable server errors (reserved). */
	const SERVER_ERROR = -6;
	/** Sent when capability or image-ownership check fails. */
	const NO_ACCESS = -7;

	private static $instance;

	/**
	 * Return the singleton instance, creating it on first call.
	 *
	 * @return static The singleton AjaxController instance.
	 */
	public static function getInstance()
	{
		if (is_null(self::$instance))
			self::$instance = new static();

		return self::$instance;
	}

	/**
	 * Return the current bulk-processor secret key from cache.
	 *
	 * The key is generated by the JS processor and stored in a short-lived cache entry
	 * (`bulk-secret`). Returns false when no key is set or the stored value is empty.
	 *
	 * Also used by the localise script to provide the initial key to JavaScript.
	 *
	 * @return string|false The processor key, or false if not set.
	 */
	public function getProcessorKey()
	{
		// Get a Secret Key.
		$cacheControl = new CacheController();
		$bulkSecret = $cacheControl->getItem('bulk-secret');

		$secretKey = $bulkSecret->getValue();
		if (is_null($secretKey) || strlen($secretKey) == 0 || $secretKey === 'null') {
			$secretKey = false;
		}
		return $secretKey;
	}

	/**
	 * Verify that the current request is the authorised JS processor.
	 *
	 * Reads `$_POST['bulk-secret']` and `$_POST['isBulk']` to determine whether this
	 * request should be treated as the active processor.  A request qualifies when:
	 * - no key is currently stored (first-come-first-served), or
	 * - the posted secret matches the stored key, or
	 * - `isBulk` is a truthy boolean string.
	 *
	 * When the caller qualifies and posts a different secret, the stored key is updated
	 * and its TTL reset to two minutes.
	 *
	 * On failure, sends a JSON error (`error = PROCESSOR_ACTIVE`) and exits; does not
	 * return false.
	 *
	 * @return void
	 */
	protected function checkProcessorKey()
	{
		$processKey = $this->getProcessorKey();
		// phpcs:ignore -- Nonce is checked
		$bulkSecret = isset($_POST['bulk-secret']) ? sanitize_text_field(wp_unslash($_POST['bulk-secret'])) : false;
		// phpcs:ignore -- Nonce is checked
		$isBulk = isset($_POST['isBulk']) ? filter_var(sanitize_text_field(wp_unslash($_POST['isBulk'])), FILTER_VALIDATE_BOOLEAN, FILTER_NULL_ON_FAILURE) : false;

		$is_processor = false;
		if ($processKey == false && $bulkSecret !== false) {
			$is_processor = true;
		} elseif ($processKey == $bulkSecret) {
			$is_processor = true;
		} elseif ($isBulk) {
			$is_processor = true;
		}

		// Save new ProcessorKey
		if ($is_processor && $bulkSecret !== $processKey) {
			$cacheControl = new CacheController();
			$cachedObj = $cacheControl->getItem('bulk-secret');

			$cachedObj->setValue($bulkSecret);
			$cachedObj->setExpires(2 * MINUTE_IN_SECONDS);
			$cachedObj->save();
		}

		if (false === $is_processor) {
			$json = new \stdClass;
			$json->message = __('Processor is active in another window', 'shortpixel-image-optimiser');
			$json->status = false;
			$json->error = self::PROCESSOR_ACTIVE; // processor active
			$this->send($json);
		}
	}

	/**
	 * Render the inline status cell HTML for a single media or custom item.
	 *
	 * Reads `$_POST['type']` ('media' or 'custom', defaults to 'media') and
	 * `$_POST['id']` (int, the image ID).  Verifies image access, then delegates to
	 * `ListMediaViewController::doColumn()` (media) or
	 * `OtherMediaViewController::doActionColumn()` (custom) via output buffering.
	 *
	 * Returns a stdClass (not sent directly — caller passes it on to `send()`):
	 * - `$json->$type->itemView`        string  Rendered HTML for the status column.
	 * - `$json->$type->is_optimizable`  bool    Whether the item can be queued.
	 * - `$json->$type->is_restorable`   bool    Whether the item can be restored.
	 * - `$json->$type->id`              int     The requested item ID.
	 * - `$json->$type->image`           array   Keys: width, height, extension.
	 * - `$json->$type->results`         null    Always null from this method.
	 * - `$json->$type->is_error`        bool    Always false from this method.
	 * - `$json->status`                 bool    Always true.
	 *
	 * @return \stdClass JSON response object.
	 */
	protected function getItemView()
	{
		// phpcs:ignore -- Nonce is checked
		$type = isset($_POST['type']) ? sanitize_text_field($_POST['type']) : 'media';
		// phpcs:ignore -- Nonce is checked
		$id = isset($_POST['id']) ? intval($_POST['id']) : false;
		$result = '';


		$item = \wpSPIO()->filesystem()->getImage($id, $type);

		$this->checkImageAccess($item);

		if ($id > 0) {
			if ($type == 'media') {
				ob_start();
				$control = ListMediaViewController::getInstance();
				$control->doColumn('wp-shortPixel', $id);
				$result = ob_get_contents();
				ob_end_clean();
			}
			if ($type == 'custom') {
				ob_start();
				$control = new OtherMediaViewController();
				$control->doActionColumn($item);
				$result = ob_get_contents();
				ob_end_clean();
			}
		}

		$json = new \stdClass;
		$json->$type = new \stdClass;
		$json->$type->itemView = $result;
		$json->$type->is_optimizable = (false !== $item) ? $item->isProcessable() : false;
		$json->$type->is_restorable = (false !== $item)  ? $item->isRestorable() : false;
		$json->$type->id = $id;
		$json->$type->image = [
			'width' => $item->get('width'), 
			'height' => $item->get('height'), 
			'extension' => $item->getExtension(), 
		];
		$json->$type->results = null;
		$json->$type->is_error = false;
		$json->status = true;

		return $json;
		// $this->send($json);
	}

	/**
	 * AJAX handler: process the next batch of items from the optimisation queue.
	 *
	 * Action: `wp_ajax_shortpixel_process_queue`.
	 *
	 * Expected `$_POST` fields:
	 * - `nonce`      string  WP nonce for action 'processing'.
	 * - `isBulk`     string  'true' or 'false'; sets bulk mode on the queue controller.
	 * - `queues`     string  Comma-separated list of queue names (default 'media,custom').
	 * - `bulk-secret` string Optional processor key for multi-tab coordination.
	 *
	 * Exits with `wp_send_json()` on success or any guard failure.
	 *
	 * @return void
	 */
	public function ajax_processQueue()
	{
		$this->checkNonce('processing');
		$this->checkActionAccess('processQueue', 'is_author');
		$this->checkProcessorKey();

		ErrorController::start(); // Capture fatal errors for us.

		// Notice that POST variables are always string, so 'true', not true.
		// phpcs:ignore -- Nonce is checked
		$isBulk = (isset($_POST['isBulk']) && $_POST['isBulk'] == 'true') ? true : false;
		// phpcs:ignore -- Nonce is checked
		$queue = (isset($_POST['queues'])) ? sanitize_text_field($_POST['queues']) : 'media,custom';

		$queues = array_filter(explode(',', $queue), 'trim');

		$control = new QueueController(['is_bulk' => $isBulk]);
		$result = $control->processQueue($queues);

		$this->send($result);
	}

	/**
	 * Attempt to claim the processor role after losing a multi-tab race.
	 *
	 * Called from `ajaxRequest()` under the `recheckActive` action.  If the previous
	 * processor has released the key (or its TTL expired), this call will succeed and
	 * the JS side can resume processing.  On failure `checkProcessorKey()` exits with
	 * `error = PROCESSOR_ACTIVE`.
	 *
	 * On success sends:
	 * - `status`  bool   true
	 * - `message` string Confirmation text.
	 *
	 * @return void
	 */
	protected function recheckActive()
	{
		// If not processor, this ends the processing and sends JSON.
		$this->checkProcessorKey();

		$json = new \stdClass;
		$json->message = __('Became processor', 'shortpixel-image-optimiser');
		$json->status = true;
		$this->send($json);
	}

	/**
	 * Primary AJAX dispatcher for screen-level actions.
	 *
	 * Action: `wp_ajax_shortpixel_ajax`.
	 *
	 * Verifies the nonce (`ajax_request`) and minimum capability (`is_author`), then
	 * dispatches to the appropriate protected method based on `$_POST['screen_action']`.
	 * Several actions re-check capability at a higher level inside their handler.
	 *
	 * Common `$_POST` fields:
	 * - `nonce`         string   WP nonce for action 'ajax_request'.
	 * - `screen_action` string   Identifies the operation to perform (see switch below).
	 * - `id`            int      Image/folder ID (most item actions).
	 * - `type`          string   'media' or 'custom' (defaults to both for status queries).
	 *
	 * All responses are sent via `send()` and the method exits.
	 *
	 * @return void
	 */
	public function ajaxRequest()
	{
		$this->checkNonce('ajax_request');
		ErrorController::start(); // Capture fatal errors for us.

		$this->checkActionAccess('ajax', 'is_author');

		// phpcs:ignore -- Nonce is checked
		$action = isset($_POST['screen_action']) ? sanitize_text_field($_POST['screen_action']) : false;
		// phpcs:ignore -- Nonce is checked
		$typeArray = isset($_POST['type'])  ? array(sanitize_text_field($_POST['type'])) : array('media', 'custom');
		// phpcs:ignore -- Nonce is checked
		$id = isset($_POST['id']) ? intval($_POST['id']) : false;

		$json = new \stdClass;
		foreach ($typeArray as $type) {
			$json->$type = new \stdClass;
			//      $json->$type->id = $id;  // This one is off because item_id belongs to results -> itemResult.
			$json->$type->results = null;
			//      $json->$type->is_error = false;
			$json->status = false;
		}

		$data = array('id' => $id, 'typeArray' => $typeArray, 'action' => $action);

		if (count($typeArray) == 1) // Actions which need specific type like optimize / restore.
		{
			$data['type'] = $typeArray[0];
			unset($data['typeArray']);
		}

		// First Item action,  alphabet.  Second general actions, alpha.
		switch ($action) {
